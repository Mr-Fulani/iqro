// The app runs the same 3D scene as the site, offline from its assets. This writes
// clients/iqro_mobile/assets/salah3d/{salah-scene.js, three.min.js, LICENSE-three.txt}
// from lib/salah3d/salah-scene.js and the pinned `three` package; the app's own page
// (index.html, salah-embed.js) is kept by hand. lib/salah-3d.test.ts fails when the
// committed copy is stale. Run from services/web: node scripts/salah3d-app-assets.ts
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

export const APP_ASSETS_DIRECTORY = new URL("../../../clients/iqro_mobile/assets/salah3d/", import.meta.url);

const BODY_START = "// salah3d:body-start\n";
const BODY_END = "// salah3d:body-end\n";

/** The site's ES module as the classic script the app's page loads after three.min.js. */
export function classicScene(module: string): string {
  const start = module.indexOf(BODY_START);
  const end = module.indexOf(BODY_END);
  const version = /^export var VERSION = '([^']+)';$/m.exec(module)?.[1];
  if (start < 0 || end < start || !version) throw new Error("salah-scene.js has lost its body markers or VERSION");
  const body = module.slice(start + BODY_START.length, end);
  return [
    "/* Generated by services/web/scripts/salah3d-app-assets.ts from services/web/lib/salah3d/salah-scene.js. Do not edit. */",
    "(function () {",
    "  'use strict';",
    "  var THREE = window.THREE;",
    "  if (!THREE) { console.error('SalahScene: THREE not loaded'); return; }",
    `${body}  window.SalahScene = { mount: mount, STEPS: STEPS, SEGMENTS: SEGMENTS, version: '${version}' };`,
    "})();",
    "",
  ].join("\n");
}

export async function salah3dAppAssets(): Promise<Map<string, Buffer>> {
  const read = (path: string) => readFile(new URL(path, import.meta.url));
  const scene = await read("../lib/salah3d/salah-scene.js");
  return new Map([
    ["salah-scene.js", Buffer.from(classicScene(scene.toString("utf8")))],
    ["three.min.js", await read("../node_modules/three/build/three.min.js")],
    ["LICENSE-three.txt", await read("../node_modules/three/LICENSE")],
  ]);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [name, content] of await salah3dAppAssets()) {
    await writeFile(new URL(name, APP_ASSETS_DIRECTORY), content);
    console.log(`wrote clients/iqro_mobile/assets/salah3d/${name}`);
  }
}
