const MAX_ORDER = 12;
// WGS 84 ellipsoid and the geomagnetic reference radius, km.
const A2 = 6378.137 ** 2;
const B2 = 6356.7523142 ** 2;
const C2 = A2 - B2;
const C4 = A2 * A2 - B2 * B2;
const REFERENCE_RADIUS = 6371.2;

const grid = () => Array.from({ length: MAX_ORDER + 1 }, () => new Array<number>(MAX_ORDER + 1).fill(0));

// Schmidt semi-normalized coefficients turned into unnormalized ones, once.
const { c, cd, k } = (() => {
  const c = grid();
  const cd = grid();
  const k = grid();
  const snorm = grid();
  for (const [n, m, g, h, dg, dh] of COEFFICIENTS) {
    c[m][n] = g;
    cd[m][n] = dg;
    if (m !== 0) {
      c[n][m - 1] = h;
      cd[n][m - 1] = dh;
    }
  }
  snorm[0][0] = 1;
  for (let n = 1; n <= MAX_ORDER; n++) {
    snorm[0][n] = (snorm[0][n - 1] * (2 * n - 1)) / n;
    let j = 2;
    for (let m = 0; m <= n; m++) {
      k[m][n] = ((n - 1) * (n - 1) - m * m) / ((2 * n - 1) * (2 * n - 3));
      if (m > 0) {
        snorm[m][n] = snorm[m - 1][n] * Math.sqrt(((n - m + 1) * j) / (n + m));
        j = 1;
        c[n][m - 1] *= snorm[m][n];
        cd[n][m - 1] *= snorm[m][n];
      }
      c[m][n] *= snorm[m][n];
      cd[m][n] *= snorm[m][n];
    }
  }
  k[1][1] = 0;
  return { c, cd, k };
})();

/** Declination in degrees east of true north at sea level, or null for invalid coordinates. */
export function magneticDeclination(latitude: number, longitude: number, at = new Date()): number | null {
  if (
    !Number.isFinite(latitude) ||
    !Number.isFinite(longitude) ||
    Math.abs(latitude) > 90 ||
    Math.abs(longitude) > 180
  ) {
    return null;
  }
  const year = at.getUTCFullYear();
  const leap = year % 400 === 0 || (year % 4 === 0 && year % 100 !== 0);
  const dt = year + (at.getTime() - Date.UTC(year, 0, 1)) / ((leap ? 366 : 365) * 86_400_000) - WMM_EPOCH;

  const latitudeRadians = (latitude * Math.PI) / 180;
  const longitudeRadians = (longitude * Math.PI) / 180;
  const sinLatitude = Math.sin(latitudeRadians);
  const cosLatitude = Math.cos(latitudeRadians);
  const sinLatitude2 = sinLatitude * sinLatitude;
  const cosLatitude2 = cosLatitude * cosLatitude;

  // Geodetic to spherical coordinates at zero altitude.
  const q = Math.sqrt(A2 - C2 * sinLatitude2);
  const ct = sinLatitude / Math.sqrt(((A2 / B2) ** 2) * cosLatitude2 + sinLatitude2);
  const st = Math.sqrt(1 - ct * ct);
  const r = Math.sqrt((A2 * A2 - C4 * sinLatitude2) / (q * q));
  const d = Math.sqrt(A2 * cosLatitude2 + B2 * sinLatitude2);
  const ca = d / r;
  const sa = (C2 * cosLatitude * sinLatitude) / (r * d);

  const sp = new Array<number>(MAX_ORDER + 1).fill(0);
  const cp = new Array<number>(MAX_ORDER + 1).fill(0);
  const pp = new Array<number>(MAX_ORDER + 1).fill(0);
  const p = grid();
  const dp = grid();
  const tc = grid();
  sp[1] = Math.sin(longitudeRadians);
  cp[0] = 1;
  cp[1] = Math.cos(longitudeRadians);
  pp[0] = 1;
  p[0][0] = 1;
  for (let m = 2; m <= MAX_ORDER; m++) {
    sp[m] = sp[1] * cp[m - 1] + cp[1] * sp[m - 1];
    cp[m] = cp[1] * cp[m - 1] - sp[1] * sp[m - 1];
  }

  const aor = REFERENCE_RADIUS / r;
  let ar = aor * aor;
  let br = 0;
  let bt = 0;
  let bp = 0;
  let bpp = 0;
  for (let n = 1; n <= MAX_ORDER; n++) {
    ar *= aor;
    for (let m = 0; m <= n; m++) {
      // Unnormalized associated Legendre polynomials and their derivatives.
      if (n === m) {
        p[m][n] = st * p[m - 1][n - 1];
        dp[m][n] = st * dp[m - 1][n - 1] + ct * p[m - 1][n - 1];
      } else if (n === 1 && m === 0) {
        p[m][n] = ct * p[m][n - 1];
        dp[m][n] = ct * dp[m][n - 1] - st * p[m][n - 1];
      } else if (n > 1) {
        if (m > n - 2) {
          p[m][n - 2] = 0;
          dp[m][n - 2] = 0;
        }
        p[m][n] = ct * p[m][n - 1] - k[m][n] * p[m][n - 2];
        dp[m][n] = ct * dp[m][n - 1] - st * p[m][n - 1] - k[m][n] * dp[m][n - 2];
      }
      // Gauss coefficients moved to the date.
      tc[m][n] = c[m][n] + dt * cd[m][n];
      if (m !== 0) tc[n][m - 1] = c[n][m - 1] + dt * cd[n][m - 1];
      const par = ar * p[m][n];
      const temp1 = m === 0 ? tc[m][n] * cp[m] : tc[m][n] * cp[m] + tc[n][m - 1] * sp[m];
      const temp2 = m === 0 ? tc[m][n] * sp[m] : tc[m][n] * sp[m] - tc[n][m - 1] * cp[m];
      bt -= ar * temp1 * dp[m][n];
      bp += m * temp2 * par;
      br += (n + 1) * temp1 * par;
      // At the geographic poles the east component needs its own recursion.
      if (st === 0 && m === 1) {
        pp[n] = n === 1 ? pp[n - 1] : ct * pp[n - 1] - k[m][n] * pp[n - 2];
        bpp += m * temp2 * ar * pp[n];
      }
    }
  }
  bp = st === 0 ? bpp : bp / st;
  // Spherical to geodetic field components: north (x) and east (y).
  const north = -bt * ca - br * sa;
  const east = bp;
  return (Math.atan2(east, north) * 180) / Math.PI;
}
