"""Generate Flutter's topic definitions from the shared web catalog.

Run with --check to verify parity without modifying files.
"""

import argparse
import json
import subprocess
from pathlib import Path

mobile = Path(__file__).resolve().parents[1]
catalog = mobile.parents[1] / "services/web/lib/dua-topic-catalog.json"
target = mobile / "lib/features/dua/dua_topic_catalog.g.dart"


def dart(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False).replace("$", r"\$")
    if isinstance(value, list):
        return "<int>[" + ", ".join(map(str, value)) + "]"
    if isinstance(value, dict):
        return "<String, String>{" + ", ".join(
            f"{dart(key)}: {dart(item)}" for key, item in value.items()
        ) + "}"
    raise TypeError(value)


rows = []
for topic in json.loads(catalog.read_text())["topics"]:
    fields = {
        "id": topic["id"],
        "collection": topic["collection"],
        "chapterNumbers": topic["chapter_numbers"],
        "titles": topic["title"],
        "descriptions": topic["description"],
    }
    if "entry_numbers" in topic:
        fields["entryNumbers"] = topic["entry_numbers"]
    rows.append("  DuaTopic(\n" + "".join(
        f"    {key}: {dart(value)},\n" for key, value in fields.items()
    ) + "  ),")
source = (
    "// Generated by tool/sync_dua_topics.py; edit services/web/lib/dua-topic-catalog.json.\n"
    "part of 'dua_topics.dart';\n\n"
    "const duaTopics = <DuaTopic>[\n" + "\n".join(rows) + "\n];\n"
)
source = subprocess.run(
    ['dart', 'format', '--output=show', '--show=none', '--summary=none',
     '--stdin-name=' + str(target)],
    input=source, text=True, capture_output=True, check=True, cwd=mobile,
).stdout
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != source:
        raise SystemExit("Dua topic definitions differ; run tool/sync_dua_topics.py")
    print("Web and Flutter topic definitions match")
else:
    target.write_text(source)
